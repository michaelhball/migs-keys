"""Extract font-independent music glyphs from LilyPond's engraved SVG output.
The SVG origin is the G/F clef anchor, or the middle line for a quarter rest.
One staff space in LilyPond output becomes 10 SVG units in our lesson renderer.
"""
from pathlib import Path
import subprocess,tempfile,xml.etree.ElementTree as E,json
root=Path(__file__).resolve().parent.parent;ns='{http://www.w3.org/2000/svg}';glyphs={}
with tempfile.TemporaryDirectory(prefix='migs-symbols-') as temp:
 for clef in ('treble','bass'):
  p=Path(temp)/clef
  p.with_suffix('.ly').write_text('\\version "2.26.0"\n\\header { tagline = ##f }\n\\score { \\new Staff { \\clef '+clef+' \\omit Staff.TimeSignature r4 } \\layout {} }\n')
  subprocess.run(['lilypond','-dbackend=svg','-o',str(p),str(p.with_suffix('.ly'))],check=True,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
  svg=E.parse(p.with_suffix('.svg')).getroot()
  direct=[path for g in svg.findall(ns+'g') for path in g.findall(ns+'path')]
  rests=[path for a in svg.findall(ns+'a') for path in a.iter(ns+'path')]
  assert len(direct)==1 and len(rests)==1
  glyphs[clef]=direct[0].get('d')
  glyphs['quarterRest']=rests[0].get('d')
assert len(glyphs)==3
(root/'public/music-symbols.js').write_text('// Generated by scripts/build-music-symbols.py using LilyPond Emmentaler.\nexport const musicGlyphs = '+json.dumps(glyphs,indent=2)+';\n')
